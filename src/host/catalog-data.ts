/**
 * The curated catalog. Every entry is tagged with its own slug so the client's
 * filter chips (`filesystem`, `playwright`, …) have a stable lowercase id.
 */
export const CURATED_CATALOG: readonly CatalogEntry[] = RAW_CURATED.map((entry) => ({
  ...entry,
  categories: [entry.slug, ...entry.categories.filter((category) => category !== entry.slug)],
}))

/** A defensive copy of the curated catalog, safe for callers to mutate. */
export function curatedCatalog(): CatalogEntry[] {
  return structuredClone([...CURATED_CATALOG])
}

/** Look up one curated entry by slug. */
export function curatedBySlug(slug: string): CatalogEntry | undefined {
  const found = CURATED_CATALOG.find((entry) => entry.slug === slug)
  return found ? structuredClone(found) : undefined
}
