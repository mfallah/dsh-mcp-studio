export type LocaleKey = (typeof LOCALE_KEYS)[number]

/** A complete dictionary for one locale. */
export type Dictionary = Record<LocaleKey, string>

/**
 * Translate one key of this namespace with optional `{name}` params.
 *
 * Deliberately narrower than the framework's `Translate<string>` so a typo in
 * a component is a compile error; the framework's bound function is assignable
 * to it because it accepts a wider key domain.
 */
export type Translate = (key: LocaleKey, params?: Record<string, unknown>) => string
